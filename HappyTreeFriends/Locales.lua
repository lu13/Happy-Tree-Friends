local clientLocale = type(GetLocale) == "function" and GetLocale() or "enUS"
local selectedLocale = locales[clientLocale] and clientLocale or "enUS"

HTF.CLIENT_LOCALE = clientLocale
HTF.LOCALE = selectedLocale
HTF.LOCALES = locales
HTF.L = {}

for key, value in pairs(locales.enUS) do
	HTF.L[key] = value
end

if selectedLocale ~= "enUS" then
	for key, value in pairs(locales[selectedLocale]) do
		HTF.L[key] = value
	end
end
